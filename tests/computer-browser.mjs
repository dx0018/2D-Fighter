import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
await mkdir('artifacts/computer',{recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try {
 const page=await browser.newPage({viewport:{width:1100,height:900}});page.setDefaultTimeout(120000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.TEST_URL||'http://localhost:5173');
 const click=a=>page.locator(`[data-action="${a}"]`).first().click();
 await click('start-computer');
 assert.equal(await page.locator('[data-setting="opponent"]').inputValue(),'computer');
 assert.equal(await page.locator('[data-action="ready"][data-player="1"]').isDisabled(),true);
 await page.click('[data-action="choose-character"][data-player="1"][data-index="2"]');
 await page.click('[data-action="ready"][data-player="0"]');
 assert.equal(await page.locator('[data-action="to-maps"]').isEnabled(),true);
 await page.selectOption('[data-setting="language"]','en');
 assert.match(await page.locator('.player-2').textContent(),/CPU ready/);
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'artifacts/computer/selection-mobile.png',fullPage:true});
 await page.setViewportSize({width:1100,height:900});
 await click('to-maps');await click('fight');
 await page.waitForFunction(()=>__POCKET__.arena?.clock>0);
 assert.match(await page.locator('.hud-p2 .hud-name').textContent(),/CPU/);
 assert.equal(await page.locator('[data-touch^="1:"]').count(),0);
 await page.evaluate(()=>{
  const g=__POCKET__.game;g.reset();g.state.phase='fighting';g.state.objects=[];
  g.state.fighters[0].x=-7;g.state.fighters[1].x=7;window.cpuCasts=[];
  const old=g.onEvent;g.onEvent=e=>{old(e);if(e.type==='cast'&&e.player===1)cpuCasts.push(e);};
 });
 await page.waitForFunction(()=>cpuCasts.length>0&&__POCKET__.game.state.fighters[1].x<6);
 await page.waitForFunction(()=>__POCKET__.game.state.fighters[0].hp<100);
 await page.locator('#battle-shell').screenshot({path:'artifacts/computer/battle.png'});
 await click('pause');
 const snapshot=await page.evaluate(()=>JSON.stringify(__POCKET__.game.state));
 await page.waitForTimeout(250);
 assert.equal(await page.evaluate(()=>JSON.stringify(__POCKET__.game.state)),snapshot);
 await click('pause');
 await page.evaluate(()=>{const g=__POCKET__.game;g.state.time=.01;g.state.fighters[0].hp=1;});
 await page.locator('.result-card').waitFor();
 await click('rematch');
 assert.match(await page.locator('.hud-p2 .hud-name').textContent(),/CPU/);
 assert.equal(await page.evaluate(()=>__POCKET__.game.state.fighters[0].hp),100);
 await click('pause');await click('reselect');
 assert.equal(await page.locator('[data-setting="opponent"]').inputValue(),'computer');
 await page.selectOption('[data-setting="opponent"]','human');
 assert.equal(await page.locator('[data-action="ready"][data-player="1"]').isEnabled(),true);
 for(const p of [0,1])await page.click(`[data-action="ready"][data-player="${p}"]`);
 await click('to-maps');await click('fight');await page.waitForFunction(()=>__POCKET__.arena?.clock>0);
 await page.evaluate(()=>{const g=__POCKET__.game;g.state.phase='fighting';g.state.fighters[1].x=5;});
 await page.keyboard.down('ArrowRight');
 await page.waitForFunction(()=>__POCKET__.game.state.fighters[1].x>6);
 await page.keyboard.up('ArrowRight');
 assert.deepEqual(errors,[]);
 console.log('PASS: CPU selection, mobile English layout, live AI damage, pause, results/rematch and local P2 keyboard.');
} finally {await browser.close();}
